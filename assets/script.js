/* ===================== Rendering ===================== */
function renderFeatured() {
  const grid = document.getElementById("featured-grid");
  grid.innerHTML = FEATURED.map(p => `
    <article class="f-card">
      <div class="f-top">
        <span class="f-icon">${p.icon}</span>
        <div class="f-links">
          ${p.demo ? `<a href="${p.demo}" target="_blank" rel="noopener">${t("proj.demo")} ↗</a>` : ""}
          <a href="${GH}${p.repo}" target="_blank" rel="noopener">${t("proj.code")} ↗</a>
        </div>
      </div>
      <h3><a href="${GH}${p.repo}" target="_blank" rel="noopener">${p.repo}</a></h3>
      <p class="f-desc">${p[currentLang] || p.en}</p>
      <div class="f-meta">
        <span><span class="dot" style="background:${p.langColor}"></span>${p.lang}</span>
        ${p.tags.map(tag => `<span>${tag}</span>`).join("")}
      </div>
    </article>
  `).join("");
}

function renderFilters() {
  const bar = document.getElementById("filter-bar");
  bar.innerHTML = FILTERS.map(f => `
    <button class="filter-btn ${f === currentFilter ? "active" : ""}" data-filter="${f}">
      ${t("filter." + f)}
    </button>
  `).join("");
  bar.querySelectorAll(".filter-btn").forEach(btn => {
    btn.addEventListener("click", () => {
      currentFilter = btn.dataset.filter;
      renderFilters();
      renderProjects();
    });
  });
}

function renderProjects() {
  const grid = document.getElementById("project-grid");
  const list = PROJECTS.filter(p => currentFilter === "all" || p.cat === currentFilter);
  grid.innerHTML = list.map(p => `
    <article class="p-card">
      <h4><a href="${GH}${p.repo}" target="_blank" rel="noopener">${p.repo}</a></h4>
      <p class="p-desc">${p[currentLang] || p.en}</p>
      <div class="f-meta">
        <span><span class="dot" style="background:${p.langColor}"></span>${p.lang}</span>
        <span class="p-stars" data-repo="${p.repo}"></span>
      </div>
    </article>
  `).join("");
  applyStars();
}

/* ===================== Language ===================== */
function setLang(lang) {
  currentLang = lang;
  localStorage.setItem("lang", lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const val = t(el.dataset.i18n);
    if (val) el.innerHTML = val;
  });

  document.getElementById("lang-en").classList.toggle("active", lang === "en");
  document.getElementById("lang-tr").classList.toggle("active", lang === "tr");

  document.title = lang === "tr"
    ? "Ata Kaan Can Olcay — Bilgisayar Mühendisi"
    : "Ata Kaan Can Olcay — Computer Engineer";

  renderFeatured();
  renderFilters();
  renderProjects();

  if (railDots.length) {
    computeRailPositions();
    onScrollFX();
  }
}

/* ===================== GitHub stars (live, best-effort) ===================== */
let starMap = null;

function applyStars() {
  if (!starMap) return;
  document.querySelectorAll(".p-stars").forEach(el => {
    const count = starMap[el.dataset.repo];
    if (count) el.textContent = `★ ${count}`;
  });
}

function fetchStars() {
  fetch("https://api.github.com/users/KNCn23/repos?per_page=100")
    .then(r => (r.ok ? r.json() : Promise.reject()))
    .then(repos => {
      starMap = {};
      repos.forEach(r => { if (r.stargazers_count > 0) starMap[r.name] = r.stargazers_count; });
      const statEl = document.getElementById("stat-repos");
      if (statEl) statEl.textContent = repos.length;
      applyStars();
    })
    .catch(() => { /* rate-limited or offline — static content still works */ });
}

